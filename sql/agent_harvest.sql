-- → ده بايبلاين المحتوى الجاي: قائمة مواضيع مقالات مدفوعة بأسئلة مستخدمين حقيقية
-- الـWorker بيكتب فيه بـ SUPABASE_SECRET (service_role) — يتجاهل RLS من غير سياسات
