def links_block(items):
    lis = "".join(
        f'<li style="margin:0 0 8px"><a href="{u}" '
        f'style="color:#e6c258;text-decoration:none;font-weight:700">{t}</a></li>'
        for t, u in items
    )
    return (
        f'<div {MARKER} data-seo-links="1" style="max-width:1100px;margin:0 auto 40px;'
        f'padding:0 20px;text-align:right">'
        f"<h2 {H2}>صفحات تستاهل تشوفها</h2>"
        f'<ul style="list-style:none;padding:0;margin:0">{lis}</ul></div>'
    )


def inject(path: Path, html_block: str) -> str:
    if not path.exists():
        return "missing"
    src = path.read_text(encoding="utf-8")
    if MARKER in src:
        return "skip"
    m = re.search(r'<div class="footer">', src)
    if not m:
        return "no-anchor"
    path.write_text(src[: m.start()] + html_block + "\n\n" + src[m.start():], encoding="utf-8")
    return "ok"


def main() -> int:
    stats = {"ok": 0, "skip": 0, "missing": 0, "no-anchor": 0}
    for name, blk in CATEGORIES.items():
        stats[inject(ROOT / "services" / name, blk)] += 1
    for name, items in LINKS.items():
        stats[inject(ROOT / name, links_block(items))] += 1
    print(stats)
    return 0


