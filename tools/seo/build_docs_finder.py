def norm(s):
    s = (s or "").replace("أ", "ا").replace("إ", "ا").replace("آ", "ا")
    s = s.replace("ة", "ه").replace("ى", "ي").replace("ئ", "ي").replace("ؤ", "و")
    s = re.sub(r"[\u064B-\u0652]", "", s)
    return re.sub(r"[^\w\s]", " ", s)


PHOTO = re.compile(r"صور(ة|ه)?\s*(شخصي|فوتو|حديث)|^\s*\d*\s*صور\s*شخصي|صور شخصيه|صورة شخصيه")


def kind_of(doc):
    """أصل / صورة / أصل وصورة / صور / غير موضّح — من نص الورقة نفسها.

    «صور» = صور شخصية تتقدم فعليًا (مش نسخة من ورقة)، فبنفصلها عن «صورة».
    """
    d = doc.strip()
    if "أصل وصورة" in d or "أصل + صورة" in d or "أصل وصورته" in d:
        return "أصل وصورة"
    if d.startswith("صورة") or "نسخة" in d or "كوبي" in d or "صورة ضوئية" in d:
        return "صور" if PHOTO.search(d) else "صورة"
    if "أصل" in d or "أصلية" in d or "اصلية" in d:
        return "أصل"
    if PHOTO.search(d):
        return "صور"
    return "غير موضّح"


def stats(html):
    out = {}
    for v, l in re.findall(
        r'<div class="stat-value">(.*?)</div><div class="stat-label">(.*?)</div>', html, re.S
    ):
        v = re.sub(r"<[^>]+>", "", v).strip()
        l = re.sub(r"<[^>]+>", "", l).strip()
        out[l] = v
    return out


def build():
    rows, missing = [], []
    for s in DOCS:
        p = SERVICES / (s["slug"] + ".html")
        html = p.read_text(encoding="utf-8")
        tags = re.findall(r'class="tag [^"]*">([^<]+)<', html)
        cats = [
            t
            for t in tags
            if not any(k in t for k in ("أونلاين", "offline", "رسم حكومي", "free", "سريع"))
        ]
        cat = cats[-1].strip() if cats else ""
        st = stats(html)
        authority = ""
        for k, v in st.items():
            if "الجهة" in k:
                authority = v
                break
        if not authority:
            authority = AUTHORITY.get(cat, "الجهة الحكومية المختصة")
        fee = next((v for k, v in st.items() if "رسوم" in k or "رسم" in k), "")
        dur = next((v for k, v in st.items() if "المدة" in k), "")
        if not dur:
            missing.append(s["slug"])
        rows.append(
            {
                "slug": s["slug"],
                "title": s["title"],
                "cat": cat,
                "link": "services/" + s["slug"] + ".html",
                "auth": authority,
                "fee": fee,
                "dur": dur,
                "docs": [{"t": d, "k": kind_of(d)} for d in s["docs"]],
                "keys": " ".join(sorted(set(norm(s["title"]).split()))),
            }
        )

    out_json = ROOT / "data/docs-finder.json"
    out_json.parent.mkdir(parents=True, exist_ok=True)
    out_json.write_text(
        json.dumps({"services": rows}, ensure_ascii=False, separators=(",", ":")),
        encoding="utf-8",
    )

    counted = {
        "services": len(rows),
        "docs": sum(len(r["docs"]) for r in rows),
        "fee": sum(1 for r in rows if r["fee"]),
        "dur": sum(1 for r in rows if r["dur"]),
        "auth_doc": sum(1 for r in rows if r["auth"] and r["auth"] not in
                        ("الجهة الحكومية المختصة",)),
    }
    print(counted)
    print("من غير مدة:", len(missing))
    return rows


if __name__ == "__main__":
    build()
