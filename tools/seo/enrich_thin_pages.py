ROOT = Path(__file__).resolve().parents[2]
MARKER = 'data-seo-enrich="1"'

WRAP = (
    '<div data-seo-enrich="1" style="max-width:1100px;margin:0 auto 40px;'
    'padding:0 20px;text-align:right">'
)
H2 = 'style="font-size:19px;color:#fff;font-weight:800;margin:0 0 10px;line-height:1.5"'
P = 'style="font-size:14.5px;color:#c3d0e6;line-height:1.9;margin:0 0 12px"'
H3 = 'style="font-size:15px;color:#e6c258;font-weight:700;margin:0 0 4px;line-height:1.6"'


def qa(q: str, a: str) -> str:
    return f'<div style="margin:0 0 14px"><h3 {H3}>{q}</h3><p {P}>{a}</p></div>'


def block(head: str, paras: list, faqs: list) -> str:
    body = [WRAP, f"<h2 {H2}>{head}</h2>"]
    body += [f"<p {P}>{t}</p>" for t in paras]
    if faqs:
        body.append(f'<h2 {H2} style="margin-top:24px">أسئلة بتتكرر</h2>')
        body += [qa(q, a) for q, a in faqs]
    body.append("</div>")
    return "\n".join(body)


