def inject(path: Path, html_block: str) -> str:
    if not path.exists():
        return "missing"
    src = path.read_text(encoding="utf-8")
    if MARKER in src:
        return "skip"
    m = re.search(r'<div class="footer">', src)
    if not m:
        return "no-anchor"
    src = src[: m.start()] + html_block + "\n\n" + src[m.start():]
    path.write_text(src, encoding="utf-8")
    return "ok"


def main() -> int:
    stats = {"ok": 0, "skip": 0, "missing": 0, "no-anchor": 0}
    for name, blk in CATEGORIES.items():
        stats[inject(ROOT / "services" / name, blk)] += 1
    for name, blk in TOOLS.items():
        stats[inject(ROOT / name, blk)] += 1
    print(stats)
    return 0


